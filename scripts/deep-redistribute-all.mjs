      const query = `
        UPDATE products
        SET category_id = $1
        WHERE deleted_at IS NULL
          AND quantity > 0
          AND category_id != $1
          AND (
            name_ar ILIKE ANY($2::text[])
            OR COALESCE(name_en, '') ILIKE ANY($2::text[])
          );
      `;

